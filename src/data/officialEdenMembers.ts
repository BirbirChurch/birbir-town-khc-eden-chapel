// Helper to format 9-digit Ethiopian mobile to standard 09...
function fmtPhone(p?: string | number): string {
  if (!p) return '';
  let str = String(p).trim().replace(/\s+/g, '');
  if (str.startsWith('9916')) str = str.replace('9916', '0916');
  if (str.startsWith('9') && str.length === 9) return '0' + str;
  if (!str.startsWith('0') && str.length >= 9) return '0' + str;
  return str;
}

